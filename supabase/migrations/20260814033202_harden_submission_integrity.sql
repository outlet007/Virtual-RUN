-- Harden submission creation against concurrent duplicate/daily-limit bypasses,
-- add application-level rate limiting, and retain an immutable admin review log.

do $$
begin
  if exists (
    select 1
    from public.submissions
    where normalized_sha256 is not null
    group by normalized_sha256
    having count(*) > 1
  ) then
    raise exception 'Cannot enforce normalized evidence uniqueness: duplicate hashes already exist';
  end if;
end
$$;

drop index if exists public.submissions_normalized_sha256_idx;

create unique index submissions_normalized_sha256_key
  on public.submissions (normalized_sha256)
  where normalized_sha256 is not null;

alter table public.submissions
  drop constraint if exists submissions_duplicate_match_type_check;

alter table public.submissions
  add constraint submissions_duplicate_match_type_check
    check (
      duplicate_match_type is null
      or duplicate_match_type in ('exact', 'normalized', 'perceptual', 'activity')
    ),
  add column activity_fingerprint text,
  add column reviewed_by uuid references public.users(id) on delete set null,
  add column reviewed_at timestamptz,
  add column review_note text,
  add constraint submissions_activity_fingerprint_format_check
    check (activity_fingerprint is null or activity_fingerprint ~ '^[0-9a-f]{64}$'),
  add constraint submissions_review_note_length_check
    check (review_note is null or char_length(review_note) <= 2000);

update public.submissions
set activity_fingerprint = encode(
  extensions.digest(
    concat_ws(
      '|',
      'v1',
      activity_type,
      activity_local_date::text,
      to_char(distance_km, 'FM999990.00'),
      coalesce(duration_sec, 0)::text
    ),
    'sha256'
  ),
  'hex'
)
where activity_fingerprint is null;

update public.submissions
set review_note = 'Legacy approval before duplicate reason enforcement',
    reviewed_at = coalesce(reviewed_at, created_at)
where status = 'approved'
  and duplicate_match_type in ('normalized', 'perceptual')
  and nullif(btrim(review_note), '') is null;

alter table public.submissions
  alter column activity_fingerprint set not null,
  add constraint submissions_duplicate_approval_reason_check
    check (
      status <> 'approved'
      or duplicate_match_type is null
      or duplicate_match_type not in ('normalized', 'perceptual')
      or char_length(btrim(coalesce(review_note, ''))) >= 10
    );

create index submissions_user_activity_fingerprint_idx
  on public.submissions (user_id, activity_fingerprint);

create index submissions_reviewed_by_idx
  on public.submissions (reviewed_by)
  where reviewed_by is not null;

