create or replace function public.consume_submission_rate_limit(
  p_user_id uuid,
  p_ip_hash text,
  p_user_limit integer default 5,
  p_ip_limit integer default 20,
  p_window_seconds integer default 600
)
returns text
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_window_start timestamptz;
begin
  if p_user_id is null
    or p_ip_hash !~ '^[0-9a-f]{64}$'
    or p_user_limit not between 1 and 100
    or p_ip_limit not between 1 and 500
    or p_window_seconds not between 60 and 86400
  then
    raise exception 'invalid_submission_rate_limit_input';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('submission-rate-user:' || p_user_id::text, 0));
  perform pg_advisory_xact_lock(hashtextextended('submission-rate-ip:' || p_ip_hash, 0));

  v_window_start := clock_timestamp() - make_interval(secs => p_window_seconds);

  delete from public.submission_rate_limit_attempts
  where created_at < clock_timestamp() - interval '1 day';

  if (
    select count(*)
    from public.submission_rate_limit_attempts
    where user_id = p_user_id
      and created_at >= v_window_start
  ) >= p_user_limit then
    return 'user_limit';
  end if;

  if (
    select count(*)
    from public.submission_rate_limit_attempts
    where ip_hash = p_ip_hash
      and created_at >= v_window_start
  ) >= p_ip_limit then
    return 'ip_limit';
  end if;

  insert into public.submission_rate_limit_attempts (user_id, ip_hash)
  values (p_user_id, p_ip_hash);

  return 'allowed';
end;
$$;

revoke all on function public.consume_submission_rate_limit(uuid, text, integer, integer, integer)
  from public, anon, authenticated;
grant execute on function public.consume_submission_rate_limit(uuid, text, integer, integer, integer)
  to service_role;

create or replace function public.create_guarded_submission(
  p_registration_id uuid,
  p_user_id uuid,
  p_source text,
  p_activity_type text,
  p_distance_km numeric,
  p_duration_sec integer,
  p_activity_date timestamptz,
  p_activity_local_date date,
  p_flag_reason text[],
  p_activity_fingerprint text,
  p_strava_activity_id text default null,
  p_evidence_url text default null,
  p_evidence_sha256 text default null,
  p_normalized_sha256 text default null,
  p_evidence_phash text default null,
  p_ocr_status text default 'not_processed',
  p_ocr_distance_km numeric default null,
  p_ocr_confidence numeric default null,
  p_ocr_raw_text text default null,
  p_ocr_processed_at timestamptz default null,
  p_phash_max_distance integer default 10
)
returns table (
  submission_id uuid,
  submission_status text,
  duplicate_type text,
  duplicate_submission_id uuid,
  duplicate_distance integer
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_daily_limit integer;
  v_existing_count integer;
  v_flag_reason text[] := coalesce(p_flag_reason, array[]::text[]);
  v_duplicate_type text;
  v_duplicate_submission_id uuid;
  v_duplicate_distance integer;
  v_status text;
  v_submission_id uuid;
begin
  if p_source not in ('upload', 'strava')
    or p_activity_type not in ('run', 'walk')
    or p_distance_km is null
    or p_distance_km <= 0
    or p_duration_sec is null
    or p_duration_sec <= 0
    or p_activity_date is null
    or p_activity_local_date is null
    or p_activity_fingerprint !~ '^[0-9a-f]{64}$'
  then
    raise exception 'invalid_submission_input';
  end if;

  if not exists (
    select 1
    from public.registrations as registrations
    join public.packages as packages on packages.id = registrations.package_id
    where registrations.id = p_registration_id
      and registrations.user_id = p_user_id
      and registrations.status = 'confirmed'
      and p_activity_type = any(packages.activity_types)
  ) then
    raise exception 'invalid_confirmed_registration';
  end if;

  if p_source = 'upload' and (
    p_evidence_url is null
    or p_evidence_sha256 !~ '^[0-9a-f]{64}$'
    or p_normalized_sha256 !~ '^[0-9a-f]{64}$'
    or p_evidence_phash !~ '^[0-9a-f]{16}$'
    or p_ocr_status not in ('matched', 'mismatch', 'unreadable', 'error')
  ) then
    raise exception 'invalid_upload_evidence';
  end if;

  if p_source = 'strava' and nullif(btrim(p_strava_activity_id), '') is null then
    raise exception 'missing_strava_activity_id';
  end if;

  if p_source = 'upload' then
    -- The global near-match lock is held only for the short database section.
    perform pg_advisory_xact_lock(hashtextextended('submission-evidence-near-match', 0));

    if exists (
      select 1 from public.submissions where evidence_sha256 = p_evidence_sha256
    ) then
      raise unique_violation using message = 'duplicate_evidence_exact';
    end if;

    if exists (
      select 1 from public.submissions where normalized_sha256 = p_normalized_sha256
    ) then
      raise unique_violation using message = 'duplicate_evidence_normalized';
    end if;
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(
      'submission-day:' || p_registration_id::text || ':' || p_activity_local_date::text,
      0
    )
  );

  select coalesce(system_settings.submission_daily_limit, 3)
  into v_daily_limit
  from public.system_settings as system_settings
  where system_settings.id = 1;

  v_daily_limit := coalesce(v_daily_limit, 3);

  select count(*)::integer
  into v_existing_count
  from public.submissions
  where registration_id = p_registration_id
    and activity_local_date = p_activity_local_date;

  if v_existing_count >= v_daily_limit
    and not ('daily_submission_limit_exceeded' = any(v_flag_reason))
  then
    v_flag_reason := array_append(v_flag_reason, 'daily_submission_limit_exceeded');
  end if;

  if p_source = 'upload' then
    select submissions.id
    into v_duplicate_submission_id
    from public.submissions as submissions
    where submissions.user_id = p_user_id
      and submissions.activity_fingerprint = p_activity_fingerprint
    order by submissions.created_at, submissions.id
    limit 1;

    if found then
      v_duplicate_type := 'activity';
      v_duplicate_distance := 0;
    else
      select near_match.submission_id, near_match.distance
      into v_duplicate_submission_id, v_duplicate_distance
      from public.find_near_duplicate_evidence(p_evidence_phash, p_phash_max_distance) as near_match
      limit 1;

      if found then
        v_duplicate_type := 'perceptual';
      end if;
    end if;
  end if;

  v_status := case
    when cardinality(v_flag_reason) = 0
      and v_duplicate_type is null
      and (p_source = 'strava' or p_ocr_status = 'matched')
    then 'approved'
    else 'flagged'
  end;

  insert into public.submissions (
    registration_id, user_id, source, activity_type, distance_km, duration_sec,
    activity_date, activity_local_date, flag_reason, activity_fingerprint,
    strava_activity_id, evidence_url, evidence_sha256, normalized_sha256,
    evidence_phash, duplicate_match_type, duplicate_match_submission_id,
    duplicate_similarity_distance, ocr_status, ocr_distance_km, ocr_confidence,
    ocr_raw_text, ocr_processed_at, status
  ) values (
    p_registration_id, p_user_id, p_source, p_activity_type, p_distance_km,
    p_duration_sec, p_activity_date, p_activity_local_date, v_flag_reason,
    p_activity_fingerprint, p_strava_activity_id, p_evidence_url,
    p_evidence_sha256, p_normalized_sha256, p_evidence_phash,
    v_duplicate_type, v_duplicate_submission_id, v_duplicate_distance,
    p_ocr_status, p_ocr_distance_km, p_ocr_confidence, p_ocr_raw_text,
    p_ocr_processed_at, v_status
  )
  returning id into v_submission_id;

  return query
  select
    v_submission_id,
    v_status,
    v_duplicate_type,
    v_duplicate_submission_id,
    v_duplicate_distance;
end;
$$;

