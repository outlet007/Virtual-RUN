create or replace function public.log_submission_review_change()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.status is distinct from old.status
    or new.reviewed_by is distinct from old.reviewed_by
    or new.review_note is distinct from old.review_note
  then
    insert into public.submission_review_audit (
      submission_id,
      reviewer_id,
      previous_status,
      new_status,
      review_note
    ) values (
      new.id,
      new.reviewed_by,
      old.status,
      new.status,
      new.review_note
    );
  end if;
  return new;
end;
$$;

revoke all on function public.log_submission_review_change() from public, anon, authenticated;

create trigger submissions_review_audit_trigger
  after update of status, reviewed_by, review_note on public.submissions
  for each row execute function public.log_submission_review_change();

create or replace function public.review_submission_guarded(
  p_submission_id uuid,
  p_reviewer_id uuid,
  p_status text,
  p_review_note text default null
)
returns table (
  submission_id uuid,
  previous_status text,
  submission_status text,
  registration_id uuid,
  user_id uuid,
  distance_km numeric
)
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_submission public.submissions%rowtype;
  v_previous_status text;
  v_note text := nullif(btrim(p_review_note), '');
begin
  if p_status not in ('approved', 'pending', 'rejected') then
    raise exception 'invalid_review_status';
  end if;

  if not exists (
    select 1
    from public.users
    where id = p_reviewer_id
      and role in ('super_admin', 'admin', 'staff')
  ) then
    raise exception 'reviewer_not_authorized';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('submission-review:' || p_submission_id::text, 0));

  select *
  into v_submission
  from public.submissions
  where id = p_submission_id
  for update;

  if not found then
    raise exception 'submission_not_found';
  end if;

  if p_status = 'approved'
    and v_submission.duplicate_match_type in ('normalized', 'perceptual')
    and char_length(coalesce(v_note, '')) < 10
  then
    raise exception 'duplicate_approval_reason_required';
  end if;

  if v_note is not null and char_length(v_note) > 2000 then
    raise exception 'review_note_too_long';
  end if;

  v_previous_status := v_submission.status;

  update public.submissions
  set status = p_status,
      reviewed_by = p_reviewer_id,
      reviewed_at = clock_timestamp(),
      review_note = v_note
  where id = p_submission_id
  returning * into v_submission;

  perform public.sync_submission_distance_points(
    p_submission_id,
    p_status = 'approved'
  );

  return query
  select
    v_submission.id,
    v_previous_status,
    v_submission.status,
    v_submission.registration_id,
    v_submission.user_id,
    v_submission.distance_km;
end;
$$;

revoke all on function public.review_submission_guarded(uuid, uuid, text, text)
  from public, anon, authenticated;
grant execute on function public.review_submission_guarded(uuid, uuid, text, text)
  to service_role;
