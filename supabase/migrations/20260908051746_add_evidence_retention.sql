create or replace function public.get_evidence_cleanup_candidates(
  p_event_id uuid default null,
  p_limit integer default 500,
  p_today date default current_date
)
returns table (
  submission_id uuid,
  evidence_path text,
  evidence_size_bytes bigint,
  event_id uuid,
  event_title text,
  event_end_date date,
  retention_days integer
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    submissions.id,
    submissions.evidence_url,
    submissions.evidence_size_bytes,
    events.id,
    events.title,
    events.end_date,
    coalesce(events.evidence_retention_days, settings.evidence_retention_days)
  from public.submissions as submissions
  join public.registrations as registrations
    on registrations.id = submissions.registration_id
  join public.events as events
    on events.id = registrations.event_id
  cross join public.system_settings as settings
  where settings.id = 1
    and settings.evidence_retention_enabled
    and submissions.evidence_url is not null
    and submissions.status in ('approved', 'rejected')
    and coalesce(events.evidence_retention_days, settings.evidence_retention_days) > 0
    and events.end_date
      + coalesce(events.evidence_retention_days, settings.evidence_retention_days)
      <= p_today
    and (p_event_id is null or events.id = p_event_id)
  order by events.end_date, submissions.created_at, submissions.id
  limit least(greatest(coalesce(p_limit, 500), 1), 1000);
$$;

revoke all on function public.get_evidence_cleanup_candidates(uuid, integer, date)
  from public, anon, authenticated, service_role;
grant execute on function public.get_evidence_cleanup_candidates(uuid, integer, date)
  to service_role;

create or replace function public.get_evidence_retention_summary(
  p_today date default current_date
)
returns table (
  event_id uuid,
  event_title text,
  event_title_en text,
  event_end_date date,
  event_retention_days integer,
  retention_days integer,
  eligible boolean,
  evidence_files bigint,
  evidence_bytes bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    events.id,
    events.title,
    events.title_en,
    events.end_date,
    events.evidence_retention_days,
    coalesce(events.evidence_retention_days, settings.evidence_retention_days),
    settings.evidence_retention_enabled
      and coalesce(events.evidence_retention_days, settings.evidence_retention_days) > 0
      and events.end_date
        + coalesce(events.evidence_retention_days, settings.evidence_retention_days)
        <= p_today,
    count(submissions.id) filter (
      where submissions.evidence_url is not null
        and submissions.status in ('approved', 'rejected')
    ),
    coalesce(sum(submissions.evidence_size_bytes) filter (
      where submissions.evidence_url is not null
        and submissions.status in ('approved', 'rejected')
    ), 0)
  from public.events as events
  cross join public.system_settings as settings
  left join public.registrations as registrations
    on registrations.event_id = events.id
  left join public.submissions as submissions
    on submissions.registration_id = registrations.id
  where settings.id = 1
    and events.end_date < p_today
  group by
    events.id,
    events.title,
    events.title_en,
    events.end_date,
    events.evidence_retention_days,
    settings.evidence_retention_enabled,
    settings.evidence_retention_days
  order by events.end_date desc, events.id;
$$;

revoke all on function public.get_evidence_retention_summary(date)
  from public, anon, authenticated, service_role;
grant execute on function public.get_evidence_retention_summary(date)
  to service_role;
