alter table public.system_settings
  add column evidence_retention_enabled boolean not null default true,
  add column evidence_retention_days integer not null default 180;

alter table public.system_settings
  add constraint system_settings_evidence_retention_days_check
  check (evidence_retention_days between 30 and 3650);

alter table public.events
  add column evidence_retention_days integer;

alter table public.events
  add constraint events_evidence_retention_days_check
  check (
    evidence_retention_days is null
    or evidence_retention_days = 0
    or evidence_retention_days between 30 and 3650
  );

comment on column public.events.evidence_retention_days is
  'NULL inherits the system setting, 0 keeps evidence forever, otherwise 30-3650 days.';

alter table public.submissions
  add column evidence_size_bytes bigint,
  add column evidence_deleted_at timestamptz,
  add column evidence_delete_reason text;

alter table public.submissions
  add constraint submissions_evidence_size_bytes_check
  check (evidence_size_bytes is null or evidence_size_bytes >= 0),
  add constraint submissions_evidence_delete_reason_check
  check (
    evidence_delete_reason is null
    or evidence_delete_reason in ('retention', 'manual')
  );

update public.submissions as submissions
set evidence_size_bytes = (objects.metadata ->> 'size')::bigint
from storage.objects as objects
where objects.bucket_id = 'run-evidence'
  and objects.name = submissions.evidence_url
  and objects.metadata ->> 'size' ~ '^[0-9]+$'
  and submissions.evidence_size_bytes is null;

create index submissions_retained_evidence_registration_idx
  on public.submissions (registration_id, created_at)
  where evidence_url is not null and status in ('approved', 'rejected');

create table public.evidence_cleanup_runs (
